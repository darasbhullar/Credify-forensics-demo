def ensemble_conservative(p_a: float, p_b: float, p_c: float, domain: str) -> Dict[str, Any]:
    if domain == "photo":
        if p_a > 0.65 and p_b > 0.65:
            prob_ai = (p_a + p_b) / 2
            return {
                "prediction": "FAKE",
                "confidence": prob_ai,
                "prob_ai": prob_ai,
                "reasoning": f"Photo domain: Strong consensus (A={p_a:.2f}, B={p_b:.2f})",
                "model_c_used": False,
                "veto_triggered": False
            }
        else:
            prob_ai = max(p_a, p_b) * 0.5
            return {
                "prediction": "REAL",
                "confidence": 1 - prob_ai,
                "prob_ai": prob_ai,
                "reasoning": f"Photo domain: Low consensus (A={p_a:.2f}, B={p_b:.2f}) - defaulting to human",
                "model_c_used": False,
                "veto_triggered": False
            }
    
    if domain == "artistic":
        if p_c < 0.35:
            return {
                "prediction": "REAL",
                "confidence": 1 - p_c,
                "prob_ai": p_c,
                "reasoning": f"Artistic: Model C veto ({p_c:.2f}) - human despite A={p_a:.2f}, B={p_b:.2f}",
                "model_c_used": True,
                "veto_triggered": True
            }
        
        if p_c > 0.7 and p_a > 0.6:
            prob_ai = max(p_c, p_a, p_b * 0.8)
            return {
                "prediction": "FAKE",
                "confidence": prob_ai,
                "prob_ai": prob_ai,
                "reasoning": f"Artistic: Strong AI consensus (C={p_c:.2f}, A={p_a:.2f})",
                "model_c_used": True,
                "veto_triggered": False
            }
        
        if p_c > 0.5 and p_a <= 0.6:
            return {
                "prediction": "REAL",
                "confidence": 0.75,
                "prob_ai": p_c * 0.5,
                "reasoning": f"Artistic: C flags ({p_c:.2f}) but A unclear ({p_a:.2f}) - cautious human",
                "model_c_used": True,
                "veto_triggered": False
            }
        
        avg = (p_a + p_b + p_c) / 3
        if avg < 0.5:
            return {
                "prediction": "REAL",
                "confidence": 1 - avg,
                "prob_ai": avg,
                "reasoning": f"Artistic: Uncertain ensemble (avg={avg:.2f}) - defaulting to human",
                "model_c_used": True,
                "veto_triggered": False
            }
        else:
            return {
                "prediction": "FAKE",
                "confidence": avg,
                "prob_ai": avg,
                "reasoning": f"Artistic: Moderate consensus (avg={avg:.2f})",
                "model_c_used": True,
                "veto_triggered": False
            }


