def _sample_indices(total_frames: int, n: int) -> List[int]:
    if total_frames <= 0:
        return []
    n = max(1, min(int(n), total_frames))
    if n == 1:
        return [total_frames // 2]
    return [int(round(i * (total_frames - 1) / (n - 1))) for i in range(n)]


def aggregate_video_results(frame_results: List[Dict[str, Any]], mode: str = "mean") -> Dict[str, Any]:
    if not frame_results:
        return {"prediction": "REAL", "confidence": 0.5, "prob_ai": 0.0, "reasoning": "No valid frames"}
    
    prob_ais = [r["prob_ai"] for r in frame_results]
    predictions = [r["prediction"] for r in frame_results]
    
    fake_count = predictions.count("FAKE")
    real_count = predictions.count("REAL")
    total = len(predictions)
    
    if mode == "max":
        final_prob = max(prob_ais)
    elif mode == "median":
        sorted_vals = sorted(prob_ais)
        final_prob = sorted_vals[len(sorted_vals) // 2]
    else:  # mean
        final_prob = sum(prob_ais) / len(prob_ais)
    
    if fake_count > 0 and real_count > 0:
        consistency_score = abs(fake_count - real_count) / total
        if consistency_score < 0.5:
            return {
                "prediction": "FAKE" if final_prob > 0.5 else "REAL",
                "confidence": 0.6,
                "prob_ai": final_prob,
                "reasoning": f"Inconsistent frames ({fake_count}/{total} FAKE, {real_count}/{total} REAL) - possible hybrid content",
                "temporal_consistency": "low"
            }
    
    label = "FAKE" if final_prob >= 0.5 else "REAL"
    confidence = final_prob if label == "FAKE" else (1.0 - final_prob)
    
    return {
        "prediction": label,
        "confidence": confidence,
        "prob_ai": final_prob,
        "reasoning": f"Video aggregation ({mode}): {fake_count}/{total} frames flagged as FAKE",
        "temporal_consistency": "high" if (fake_count == 0 or real_count == 0) else "medium"
    }


