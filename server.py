def _mime_from_name(name: str) -> str:
    guess = mimetypes.guess_type(name or "")[0]
    return guess or "application/octet-stream"

def _resolve_mime(content_type: Optional[str], name: str) -> str:
    if content_type:
        return content_type
    return _mime_from_name(name)

def parse_c2pa_ai_signal(store: Dict[str, Any]) -> Dict[str, Any]:
    out = {
        "has_c2pa": False,
        "validation_state": None,
        "is_valid": False,
        "ai_claimed": False,
        "issuer": "",
    }
    if not isinstance(store, dict):
        return out

    active_id = store.get("active_manifest")
    manifests = store.get("manifests", {}) or {}
    validation_state = store.get("validation_state") or store.get("validation_status")

    out["has_c2pa"] = bool(active_id) and isinstance(manifests, dict) and len(manifests) > 0
    out["validation_state"] = validation_state
    out["is_valid"] = str(validation_state or "").strip().lower() == "valid"

    def scan_manifest(man: Dict[str, Any]) -> bool:
        assertions = man.get("assertions", []) or []
        for a in assertions:
            if a.get("label") != "c2pa.actions.v2":
                continue
            data = a.get("data", {}) or {}
            actions = data.get("actions", []) or []
            for act in actions:
                dst = str(act.get("digitalSourceType", "")).lower()
                desc = str(act.get("description", "")).lower()
                action = str(act.get("action", "")).lower()
                if "trainedalgorithmicmedia" in dst:
                    return True
                if "generative ai" in desc or "generated by" in desc:
                    return True
                if action == "c2pa.created" and (
                    "algorithmic" in dst or "synthetic" in dst or "generated" in desc
                ):
                    return True
        return False

    active = manifests.get(active_id, {}) if active_id else {}
    sig = active.get("signature_info", {}) or {}
    out["issuer"] = str(sig.get("issuer") or "").strip()

    ai_claimed = scan_manifest(active)
    if not ai_claimed:
        for _, man in manifests.items():
            if not isinstance(man, dict):
                continue
            if scan_manifest(man):
                ai_claimed = True
                if not out["issuer"]:
                    sig2 = (man.get("signature_info") or {})
                    out["issuer"] = str(sig2.get("issuer") or "").strip()
                break

    out["ai_claimed"] = bool(ai_claimed)
    return out

def extract_c2pa_info(raw: bytes, filename: str, content_type: Optional[str] = None) -> Dict[str, Any]:
    base: Dict[str, Any] = {
        "has_c2pa": False,
        "validation_state": None,
        "is_valid": False,
        "ai_claimed": False,
        "issuer": "",
        "_error": None,
        "_store_keys": None,
    }
    if not HAVE_C2PA or not raw:
        return base

    try:
        mime_type = _resolve_mime(content_type, filename)
        with io.BytesIO(raw) as bio:
            bio.seek(0)
            try:
                with C2PAReader(mime_type, stream=bio) as r:  # type: ignore
                    store_json = r.json()
            except TypeError:
                bio.seek(0)
                with C2PAReader(mime_type, bio) as r:  # type: ignore
                    store_json = r.json()

        store = json.loads(store_json) if isinstance(store_json, str) else store_json
        if isinstance(store, dict):
            base["_store_keys"] = list(store.keys())

        info = parse_c2pa_ai_signal(store if isinstance(store, dict) else {})
        base.update(info)
        return base

    except Exception as e:
        base["_error"] = f"Reader error: {type(e).__name__}: {e}"
        return base


