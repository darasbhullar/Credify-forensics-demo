@app.post("/api/analyze/video")
async def analyze_video(
    request: Request,
    frames: int = Form(5),
    agg: str = Form("mean"),
    file: UploadFile = File(...),
) -> Dict[str, Any]:
    """Protected video evaluation pipeline."""
    if not check_auth(request):
        raise HTTPException(status_code=401, detail="Unauthorized session. Please log in first.")

    raw = await file.read()
    if not raw:
        raise HTTPException(status_code=400, detail="Empty upload.")
    if len(raw) > 200 * 1024 * 1024:
        raise HTTPException(status_code=413, detail="File too large (max ~200MB).")

    c2pa_info = extract_c2pa_info(raw, file.filename or "", file.content_type)

    if c2pa_info.get("is_valid") and c2pa_info.get("ai_claimed"):
        return {
            "label": "FAKE",
            "confidence": 0.99,
            "prob_ai": 0.99,
            "fps": 0,
            "frames_ok": 0,
            "frames_total": 0,
            "reasoning": "C2PA cryptographic proof: AI-generated video",
            "c2pa": c2pa_info
        }
    elif c2pa_info.get("is_valid") and not c2pa_info.get("ai_claimed"):
        return {
            "label": "REAL",
            "confidence": 0.99,
            "prob_ai": 0.01,
            "fps": 0,
            "frames_ok": 0,
            "frames_total": 0,
            "reasoning": "C2PA cryptographic proof: Authentic video capture",
            "c2pa": c2pa_info
        }

    with tempfile.NamedTemporaryFile(delete=False, suffix=".mp4") as tmp:
        tmp.write(raw)
        tmp_path = tmp.name

    cap = cv2.VideoCapture(tmp_path)
    if not cap.isOpened():
        cap.release()
        raise HTTPException(status_code=400, detail="Could not open video file.")

    total = int(cap.get(cv2.CAP_PROP_FRAME_COUNT)) or 0
    fps = float(cap.get(cv2.CAP_PROP_FPS) or 0.0)

    idxs = _sample_indices(total, frames)
    if not idxs:
        cap.release()
        raise HTTPException(status_code=400, detail="Video appears to have 0 readable frames.")

    frame_results: List[Dict[str, Any]] = []
    per_frame_details: List[Dict[str, Any]] = []

    for frame_idx in idxs:
        cap.set(cv2.CAP_PROP_POS_FRAMES, frame_idx)
        ok, frame = cap.read()
        if not ok or frame is None:
            per_frame_details.append({
                "frame": frame_idx,
                "status": "read_failed",
                "p_a": 0.0, "p_b": 0.0, "p_c": 0.0, "prob_ai": 0.0
            })
            continue

        frame_rgb = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
        pil = Image.fromarray(frame_rgb).convert("RGB")

        try:
            p_a = infer_a(pil)
            p_b = infer_b(pil)
            domain = detect_image_domain(pil)
            p_c = infer_c(pil) if domain == "artistic" else 0.5
                
            result = ensemble_conservative(p_a, p_b, p_c, domain)
            frame_results.append(result)
            
            per_frame_details.append({
                "frame": frame_idx,
                "status": result["prediction"],
                "p_a": round(p_a, 4),
                "p_b": round(p_b, 4),
                "p_c": round(p_c, 4) if domain == "artistic" else None,
                "domain": domain,
                "prob_ai": round(result["prob_ai"], 4),
                "reasoning": result["reasoning"]
            })
        except Exception as e:
            per_frame_details.append({
                "frame": frame_idx,
                "status": "inference_error",
                "error": str(e),
                "p_a": 0.0, "p_b": 0.0, "p_c": 0.0, "prob_ai": 0.0
            })

    cap.release()

    if not frame_results:
        raise HTTPException(status_code=500, detail="Inference failed on all sampled frames.")

    agg_mode = agg.lower()
    if agg_mode not in {"mean", "max", "median"}:
        agg_mode = "mean"

    final_result = aggregate_video_results(frame_results, agg_mode)
    frames_ok = sum(1 for f in per_frame_details if f["status"] in ["REAL", "FAKE"])

    return {
        "label": final_result["prediction"],
        "confidence": round(final_result["confidence"], 4),
        "prob_ai": round(final_result["prob_ai"], 4),
        "fps": fps,
        "frames_ok": frames_ok,
        "frames_total": len(idxs),
        "agg": agg_mode,
        "temporal_consistency": final_result.get("temporal_consistency", "unknown"),
        "reasoning": final_result["reasoning"],
        "per_frame": per_frame_details,
        "filename": file.filename or "",
        "c2pa": {
            "has_c2pa": bool(c2pa_info.get("has_c2pa")),
            "validation_state": c2pa_info.get("validation_state"),
            "is_valid": bool(c2pa_info.get("is_valid")),
            "ai_claimed": bool(c2pa_info.get("ai_claimed")),
            "issuer": c2pa_info.get("issuer") or "",
            "_error": c2pa_info.get("_error"),
            "_store_keys": c2pa_info.get("_store_keys"),
        },
    }


